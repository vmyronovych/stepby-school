import type { Point, VectorEngine } from '../types';
/* § 6: напрямлені відрізки. Геометричні дані — цілі клітинки сітки. */
export const VectorLesson = (() => {
  const presets: VectorEngine['presets'] = {
    equal: {
      name: 'Рівні вектори',
      points: [
        [3, 8],
        [7, 5],
        [10, 9],
        [14, 6],
      ],
    },
    parallel: {
      name: 'Співнапрямлені, різні модулі',
      points: [
        [3, 8],
        [7, 6],
        [9, 7],
        [15, 4],
      ],
    },
    opposite: {
      name: 'Протилежні напрями, однакові модулі',
      points: [
        [3, 8],
        [7, 5],
        [14, 5],
        [10, 8],
      ],
    },
    crossing: {
      name: 'Неколінеарні, однакові модулі',
      points: [
        [3, 8],
        [7, 5],
        [11, 4],
        [14, 8],
      ],
    },
    zero: {
      name: 'Один нульовий вектор',
      points: [
        [4, 7],
        [4, 7],
        [10, 8],
        [14, 5],
      ],
    },
    zeros: {
      name: 'Два нульові вектори',
      points: [
        [4, 7],
        [4, 7],
        [12, 6],
        [12, 6],
      ],
    },
  };
  const symbol = (name: string) =>
    `<span class="vec-symbol" aria-label="вектор ${name}">${name}</span>`;
  const ab = symbol('AB'),
    cd = symbol('CD');
  const lessons = [
    {
      title: 'Вектор',
      preset: 'equal',
      rule: `<b>Вектор — це напрямлений відрізок.</b> У ${ab} точка A — початок, а B — кінець. Стрілка показує напрям від A до B.`,
      note: `Вектор позначають двома великими літерами зі стрілкою або однією малою: <span class="vec-symbol">a</span>. Якщо A і B збігаються, маємо нульовий вектор.`,
      task: 'Перемісти B. Простеж, як змінюється стрілка від A до B.',
    },
    {
      title: 'Модуль',
      preset: 'equal',
      rule: `<b>Модуль вектора — довжина його відрізка.</b> Записуємо |${ab}| = AB. Модуль завжди невід’ємний.`,
      note: 'Одна сторона клітинки — одна одиниця довжини. Нульовий вектор має модуль 0. Модулі двох векторів можуть бути рівними, навіть коли напрями різні.',
      task: 'Обери точку B та пересувай її кнопками. Порівняй довжини двох стрілок.',
    },
    {
      title: 'Напрям',
      preset: 'opposite',
      rule: `<b>Напрям читаємо від початку до кінця.</b> Для різних точок A і B вектори ${ab} і ${symbol('BA')} мають протилежні напрями.`,
      note: 'Ненульові колінеарні вектори можуть бути співнапрямленими або протилежно напрямленими. Напрям нульового вектора не визначають.',
      task: 'Натисни «Поміняти A і B». Модуль залишиться тим самим, а напрям зміниться.',
    },
    {
      title: 'Колінеарність',
      preset: 'parallel',
      rule: '<b>Колінеарні вектори лежать на одній прямій або на паралельних прямих.</b> Їхні модулі можуть бути різними.',
      note: 'Ненульові колінеарні вектори мають однаковий або протилежний напрям. Нульовий вектор вважають колінеарним із будь-яким вектором.',
      task: 'Увімкни прямі векторів. Перемісти D на одну клітинку вбік і перевір колінеарність.',
    },
    {
      title: 'Рівність',
      preset: 'equal',
      rule: '<b>Ненульові вектори рівні, якщо вони співнапрямлені та мають однакові модулі.</b> Розташування на площині не впливає на рівність.',
      note: 'Однакової довжини недостатньо: потрібен і однаковий напрям. Усі нульові вектори рівні між собою.',
      task: 'Натисни «Перенести CD». Обидві точки змістяться разом. Чи збережеться рівність?',
    },
  ];
  function classify(points: Point[]) {
    const [a, b, c, d] = points;
    const u = [b[0] - a[0], b[1] - a[1]],
      v = [d[0] - c[0], d[1] - c[1]];
    const n = u[0] ** 2 + u[1] ** 2,
      m = v[0] ** 2 + v[1] ** 2;
    const zero = n === 0 || m === 0;
    const collinear = u[0] * v[1] === u[1] * v[0];
    const dot = u[0] * v[0] + u[1] * v[1];
    return {
      n,
      m,
      zero,
      collinear,
      same: !zero && collinear && dot > 0,
      opposite: !zero && collinear && dot < 0,
      equal: u[0] === v[0] && u[1] === v[1],
    };
  }
  function length(n: number) {
    const root = Math.sqrt(n);
    return Number.isInteger(root)
      ? String(root)
      : `√${n} ≈ ${root.toFixed(2).replace('.', ',')}`;
  }
  return { classify, length, presets, lessons };
})();

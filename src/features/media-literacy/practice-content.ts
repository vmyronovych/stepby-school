const option = (text: string, feedback: string): PracticeOption => ({
  text,
  feedback,
});
const reason = (
  action: number,
  text: string,
  feedback: string,
): PracticeReason => ({ action, text, feedback });
type ChatLine = [string, string, Pick<ChatMessage, 'reactions' | 'forwarded'>?];
const chat = (name: string, lines: ChatLine[]): ChatStory => ({
  name,
  subtitle: 'Вигадана навчальна ситуація',
  messages: lines.map(([author, text, details], i) => ({
    ...details,
    author,
    text,
    time: `15:${String(10 + i).padStart(2, '0')}`,
    outgoing: i % 2 === 1,
  })),
});

const conversation = (
  name: string,
  lines: [string, string][],
  art: ComicStripId,
): ChatStory => ({
  ...chat(name, lines),
  messages: chat(name, lines).messages.map((message, index) => ({
    ...message,
    comicArt: comicStrip(art, index % 2 === 0 ? 0 : 1),
  })),
  medium: 'in-person',
  adultAuthors: lines
    .map(([author]) => author)
    .filter((author) => ['Мама', 'Тато'].includes(author)),
});


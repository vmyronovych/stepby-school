import { McarFigure } from './McarFigure';

export function LineRuleVisual({
  number,
  active = true,
}: {
  number: number;
  active?: boolean;
}) {
  if (number < 25 || number > 30) return null;
  return (
    <section
      className="robotics-line-rule"
      aria-label="Схема правила руху по лінії"
    >
      <McarFigure
        src="assets/robotics/line-decision.svg"
        width={900}
        height={720}
        active={active}
        alt="Послідовна перевірка: центр бачить темне — вперед; інакше лівий — ліворуч; інакше правий — праворуч; інакше — стоп. Виконується одна обрана дія."
        caption={
          number === 25
            ? 'Одне зчитування → одна обрана дія → коротке очікування → Стоп. У програмі цього заняття циклу ще немає.'
            : number === 26
              ? 'У кожному повторенні заново зчитуємо покази й обираємо одну дію. Без лінії — Стоп; коли лінія повертається, наступне рішення може відновити рух.'
              : 'Це правило виконується лише за дозволеного руху. Втрата лінії вимикає мотори та забирає дозвіл до нового старту.'
        }
      />
      {number >= 27 && (
        <McarFigure
          src="assets/robotics/line-stop-memory.svg"
          width={900}
          height={390}
          active={active}
          alt="Два стани: рух дозволений та стоп запам’ятовано. Втрата лінії переводить у стоп; повернення лінії не відновлює рух. Лише новий старт повертає дозвіл."
          caption="Змінна зберігає стан між повтореннями. Після зникнення лінії простого повернення датчика над нею недостатньо для руху."
        />
      )}
    </section>
  );
}

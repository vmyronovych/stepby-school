import { practiceSources, type PracticeTask } from '../content/practice';
export function PracticeTeacherGuide({ tasks }: { tasks: PracticeTask[] }) {
  const sources = [...new Set(tasks.flatMap((task) => task.sourceIds))];
  return (
    <section className="media-panel media-practice-guide">
      <h3>Практика учня: нові ситуації та ключі</h3>
      <p>
        На проєкторі пояснюємо правило, а в практиці перевіряємо його
        застосування за інших обставин. Зміна стосується прохання, умов або ролі
        героя, а не лише його імені. Серед завдань є звичайні, прийнятні
        ситуації: відповідь «відмовитися від усього» не працює.
      </p>
      <p>
        <strong>Як провести за 12 хвилин:</strong> до 9 хвилин — самостійні
        спроби, останні 3 — повернення до складного прикладу й коротке
        пояснення. Дитина обирає дію, потім причину; зворотний зв’язок
        відкривається лише після обох виборів. За потреби читайте текст, не
        підказуючи варіант. Усне пояснення рівноцінне; завершення всіх карток не
        є змаганням.
      </p>
      <p>
        <strong>Що перевіряємо:</strong> обґрунтоване рішення, а не впізнавання
        відповіді з показу. У програмі картка завершена лише після правильного
        вибору дії й причини. Позначка після повторної спроби показує навчальний
        прогрес, а не самостійне розв’язання з першого разу. Для оцінювання
        вислухайте пояснення й відзначте, чи була потрібна допомога.
      </p>
      <p>
        <strong>Як підтримати:</strong> на «усе небезпечне» попросіть назвати
        конкретне прохання; на «бо це друг» — пояснити, чи потрібен йому секрет;
        на «так сказав учитель» — пов’язати дію з можливим наслідком. Після
        помилки дайте прочитати підказку й спробувати знову. За потреби
        поверніться до демонстраційного прикладу, але позначте таку спробу як
        виконану з підтримкою.
      </p>
      <p>
        <strong>«Чому ти так думаєш?»:</strong> це запитання не підтверджує
        правильності першого вибору. Серед пояснень є причини і правильних, і
        помилкових рішень. Після «Перевірити» відгук відповідає саме на обране
        пояснення дитини, навіть коли обидва вибори помилкові. Він розбирає
        конкретну думку через знайому ситуацію, пояснює, чого ще не знаємо, та
        пропонує наступний крок. Якщо пояснення правильне, а дія ні, запитуємо:
        «А як тоді вчинити?» Кілька простих речень корисніші за команду змінити
        кнопку. Наслідки можна відкрити окремо. Узгоджена помилкова пара теж
        потребує обговорення — вона не завершує завдання. Запитайте: «Що
        допомогло б тобі перевірити цю думку?» Для дітей, яким ще складно
        читати, прочитайте варіанти вголос і дайте спочатку пояснити своїми
        словами.
      </p>
      <p>
        <strong>Факт, думка та припущення:</strong> факт — те, що справді є або
        сталося і що можна підтвердити; думка — особиста оцінка («Мені
        подобається ця гра»); припущення — можливе пояснення, якого ще не
        перевірили («Може, стіл потім прибрали»). Повідомлення «Завтра уроків
        немає» можна перевірити, але до перевірки це ще не встановлений факт. Не
        називайте всі неперевірені повідомлення думками, а всі думки —
        помилками. Запитуйте: «Що ми знаємо? Що лише припускаємо? Як це
        перевірити?» У темах про згоду й паролі пов’язуйте ці запитання з
        конкретною ситуацією. Почуття дитини не потребують доказів; відмова
        поширювати її фото не потребує виправдання.
      </p>
      <p>
        <strong>Як обговорювати наслідки:</strong> пов’яжіть дію зі знайомим
        дитині життям — спільними планами, часом із близькими, переживаннями
        друга. Запитайте: «Кого ще це може торкнутися і як?» Не перетворюйте це
        на звинувачення «через тебе мама засмутиться». Добрий намір може мати
        небажаний наслідок, а помилку можна виправляти з підтримкою. Дорослого
        можна покликати й після помилки; це не тягар і не покарання. Розрізняйте
        факти історії та продовження, яке лише уявляєте.
      </p>
      {tasks.map((task, index) => (
        <section className="media-teacher-card" key={task.id}>
          <h4>
            {index + 1}. {task.title}
          </h4>
          <p>
            <strong>Навичка:</strong> {task.skill}
          </p>
          <p>
            <strong>Що змінилося порівняно з показом:</strong> {task.transfer}
          </p>
          <p>{task.context}</p>
          <p>
            {task.chat.messages
              .map((message) => `${message.author}: ${message.text}`)
              .join(' ')}
          </p>
          <p>
            <strong>Дія:</strong> {task.actions[task.correctAction].text}
          </p>
          <p>
            <strong>Причина:</strong> {task.reasons[task.correctReason].text}
          </p>
          <p>
            <strong>Можливий наслідок:</strong> {task.consequence}
          </p>
          <p>
            <strong>Коротке пояснення дітям:</strong> «{task.rule}»
          </p>
          <details>
            <summary>Пояснення всіх варіантів і типових помилок</summary>
            {task.actions.map((item) => (
              <p key={item.text}>
                <strong>{item.text}</strong> — {item.feedback}
              </p>
            ))}
            {task.reasons.map((item) => (
              <p key={item.text}>
                <strong>Думка:</strong> «{item.text}»<br />
                <strong>Пояснює вибір:</strong> «
                {task.actions[item.action].text}»<br />
                <strong>Що сказати після перевірки:</strong> {item.feedback}
              </p>
            ))}
          </details>
          <p className="media-muted">
            Основа:{' '}
            {task.sourceIds.map((id) => practiceSources[id].title).join('; ')}.
            Сюжет і діалог вигадані.
          </p>
        </section>
      ))}
      <h4>Джерела й межі адаптації</h4>
      <p>
        Це авторські навчальні ситуації за мотивами рекомендацій, а не перекази
        історій конкретних дітей. Задокументований випадок FTC окремо позначено
        нижче. Перевірено 13 листопада 2026 року.
      </p>
      {sources.map((id) => (
        <p key={id}>
          <a href={practiceSources[id].url} target="_blank" rel="noreferrer">
            {practiceSources[id].title}
          </a>
          . {practiceSources[id].note}
        </p>
      ))}
    </section>
  );
}

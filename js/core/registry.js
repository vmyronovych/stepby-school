/* =========================================================
   РЕЄСТР ІНСТРУМЕНТІВ — єдина точка під'єднання
   ---------------------------------------------------------
   Один інструмент = один файл js/tools/<id>.js, який реєструє себе сам.
   Оболонка (js/ui/tool-shell.js) НЕ знає про конкретні інструменти —
   вона лише викликає функції з цього запису. Додати інструмент =
   створити файл + додати <script> у index.html. Більше нічого.

   Порядок реєстрації (= порядок <script>) визначає порядок відображення.
   ---------------------------------------------------------
   КОНТРАКТ ЗАПИСУ

   Довідник (для карток і чипів):
     name, icon, color, bg

   Модель і рендер (серце інструмента):
     build(cfg)       -> model   Чиста модель без DOM: {steps:[{text, …}], …}.
                                 Кидає РЯДОК-пояснення, якщо умова некоректна —
                                 його побачить учень. Кине 'bad' → покажемо errorHint.
     view(model, ctx) -> html    Рендер ОДНОГО кроку. ctx = {step, index, anim}.

   Умова (панель ліворуч, потік учня):
     inputs(cfg)   -> html       Поля вводу; id полів — на розсуд інструмента.
     read(v)       -> cfg        Зчитування цих полів; v('i_a') → значення.

   Кабінет вчителя (наразі від'єднаний від UI, але контракт тримаємо цілим):
     summary(cfg)      -> string
     editorFields(cfg) -> html
     readEditor(v)     -> cfg

   Анімація (необов'язково — інструмент без польотів їх просто не оголошує):
     prepare(model, from, to) -> anim|null   ДО перемальовування: читає позиції
                                             з живого DOM старого кроку.
                                             Не викликається у «спокійному режимі».
     animate(model, ctx)                     ПІСЛЯ перемальовування, у rAF.

   Необов'язкове:
     errorHint  — текст, якщо build кинув 'bad'
   ========================================================= */
const TOOL_REQUIRED = ['name','icon','color','bg','build','view','inputs','read','summary','editorFields','readEditor'];

function registerTool(id, def){
  if(DB.tools[id]) throw new Error(`Інструмент «${id}» уже зареєстровано`);
  const missing = TOOL_REQUIRED.filter(k=>def[k]==null);
  if(missing.length) throw new Error(`Інструмент «${id}»: не заповнено ${missing.join(', ')}`);
  DB.tools[id] = Object.assign({id}, def);
}

// Запис поточного (або вказаного) інструмента.

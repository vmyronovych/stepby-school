/* Готові розбори вправ 6.1–6.13. Формули й письмо — зі спільного ядра. */
const RP = (()=>{
  const N=F.num, V=F.x, B=F.paren, add=F.add, sub=F.sub, mul=F.mul, div=F.div;
  const P=(a,n,d=1)=>F.pow(typeof a==='string'?V(a):typeof a==='number'?N(a):a,typeof n==='number'?qAst(Q(n,d)):n);
  const R=(n,a)=>F.root(n,typeof a==='string'?V(a):typeof a==='number'?N(a):a);
  const D=s=>({t:'num',q:qFromStr(s),raw:s.replace('.',',')});
  const dec=(a,s)=>F.pow(typeof a==='number'?N(a):a,D(s));
  const times=(...xs)=>xs.reduce((a,b)=>mul(a,b));
  const a=V('a'),b=V('b'),c=V('c'),m=V('m'),n=V('n');
  const examples=[];
  const ex=(group,title,condition,rows)=>examples.push({group,title,condition,rows});
  const row=(text,...parts)=>({text,parts});
  ex('6.1','Подай степінь у вигляді кореня','',[
    row('Записуємо степінь із дробовим показником.',P(5,1,3)),
    row('Знаменник показника задає показник кореня. Чисельник 1 можна не писати.',P(5,1,3),R(3,5)),
  ]);
  ex('6.2','Подай від’ємний степінь у вигляді кореня','',[
    row('Маємо від’ємний дробовий показник.',P(3,-1,9)),
    row('За означенням переносимо чисельник показника під корінь.',P(3,-1,9),R(9,P(3,-1))),
    row('Від’ємний показник дає обернене число.',R(9,P(3,-1)),div(N(1),R(9,3))),
  ]);
  ex('6.3','Подай корінь у вигляді степеня','x ≥ 0',[
    row('Квадратний корінь визначений, коли x ≥ 0.',R(2,'x')),
    row('Показник квадратного кореня — 2. Тому показник степеня дорівнює 1/2.',R(2,'x'),P('x',1,2)),
  ]);
  ex('6.4','Запиши корінь із від’ємним степенем','m > 0',[
    row('Від’ємний показник виключає нуль. Парний корінь також виключає від’ємні m.',R(14,P('m',-9))),
    row('Показник підкореневого виразу ділимо на показник кореня.',R(14,P('m',-9)),P('m',-9,14)),
  ]);
  ex('6.5','Знайди значення степеня','',[
    row('Щоб обчислити степінь, спочатку добудемо кубічний корінь.',P(27,4,3)),
    row('Добуваємо кубічний корінь із 27.',P(27,4,3),P(B(R(3,27)),4),P(3,4)),
    row('Підносимо 3 до четвертого степеня.',P(3,4),N(81)),
  ]);
  ex('6.6','Обчисли степінь десяткового дробу','',[
    row('Перетворюємо десятковий дріб на звичайний.',P(D('0.125'),-2,3),P(B(div(N(1),N(8))),-2,3)),
    row('Кубічний корінь з 1/8 дорівнює 1/2.',P(B(div(N(1),N(8))),-2,3),P(B(div(N(1),N(2))),-2)),
    row('Обертаємо дріб і підносимо до квадрата.',P(B(div(N(1),N(2))),-2),P(2,2),N(4)),
  ]);
  ex('6.7','Застосуй властивість добутку степенів','',[
    row('Основи однакові, тому показники додаємо.',times(dec(3,'1.8'),dec(3,'-2.6'),dec(3,'2.8'))),
    row('Обчислюємо суму показників: 1,8 − 2,6 + 2,8 = 2.',P(3,2)),
    row('Обчислюємо квадрат числа 3.',P(3,2),N(9)),
  ]);
  ex('6.8','Застосуй степінь степеня та частку','',[
    row('Спочатку перемножимо показники степеня степеня.',div(P(B(dec(7,'-0.7')),8),dec(7,'-7.6'))),
    row('Маємо (−0,7) · 8 = −5,6.',div(P(7,-56,10),P(7,-76,10))),
    row('При діленні віднімаємо показники: −5,6 − (−7,6) = 2.',P(7,2)),
    row('Обчислюємо квадрат числа 7.',P(7,2),N(49)),
  ]);
  const u=mul(N(3),P('b',2,3)),v=P('c',3,2);
  ex('6.9','Розкрий дужки: різниця квадратів','b ≥ 0; c ≥ 0',[
    row('Використаємо формулу (u − v)(u + v) = u² − v².',mul(B(sub(u,v)),B(add(u,v)))),
    row('Підносимо кожен із двох виразів до квадрата.',sub(P(B(u),2),P(B(v),2))),
    row('Перемножуємо показники: (2/3) · 2 = 4/3, (3/2) · 2 = 3.',sub(mul(N(9),P('b',4,3)),P('c',3))),
  ]);
  ex('6.10','Розкрий дужки зі степенями 0,5','m ≥ 0; n ≥ 0',[
    row('Показник 0,5 дорівнює 1/2. Застосуємо різницю квадратів.',mul(B(add(dec(m,'0.5'),dec(n,'0.5'))),B(sub(dec(m,'0.5'),dec(n,'0.5'))))),
    row('Квадрати степенів із показником 1/2 дорівнюють їхнім основам.',sub(P(B(P('m',1,2)),2),P(B(P('n',1,2)),2))),
    row('Одержуємо різницю m і n.',sub(m,n)),
  ]);
  ex('6.11','Обчисли суму та різницю степенів','',[
    row('Переводимо десяткові показники у звичайні дроби.',sub(add(dec(25,'1.5'),P(B(D('0.25')),-1,2)),dec(81,'0.75'))),
    row('Маємо показники 3/2, −1/2 та 3/4.',sub(add(P(25,3,2),P(B(div(N(1),N(4))),-1,2)),P(81,3,4))),
    row('Обчислюємо кожний степінь: 125, 2 та 27.',sub(add(N(125),N(2)),N(27))),
    row('Виконуємо додавання та віднімання.',N(100)),
  ]);
  ex('6.12','Зведи степені до спільної основи','',[
    row('Подамо всі основи як степені числа 5.',times(dec(625,'-1.25'),dec(25,'1.5'),P(125,2,3))),
    row('625 = 5⁴, 25 = 5², 125 = 5³.',times(P(B(P(5,4)),-5,4),P(B(P(5,2)),3,2),P(B(P(5,3)),2,3))),
    row('Перемножуємо показники в кожному множнику.',times(P(5,-5),P(5,3),P(5,2))),
    row('Додаємо показники: −5 + 3 + 2 = 0. Нульовий степінь ненульового числа дорівнює 1.',P(5,0),N(1)),
  ]);
  const factor=Object.assign(B(sub(P('a',1,2),N(5))),{fid:'rp-cancel-top'});
  const denominator=Object.assign(sub(P('a',1,2),N(5)),{fid:'rp-cancel-bottom'});
  const factored=div(mul(P('a',1,2),factor),denominator);
  ex('6.13','Скороти дріб зі степенями','a ≥ 0; a ≠ 25',[
    row('Потрібно a ≥ 0. Знаменник не може дорівнювати нулю, тому a ≠ 25.',div(sub(a,mul(N(5),P('a',1,2))),sub(P('a',1,2),N(5)))),
    row('Виносимо a^(1/2) за дужки в чисельнику.',factored),
    Object.assign(row('Закреслюємо однакові множники в чисельнику та знаменнику. Вони ненульові, бо a ≠ 25.',factored),{cancelRow:1}),
    row('Скорочуємо спільний ненульовий множник. Обмеження a ≠ 25 зберігаємо.',P('a',1,2),R(2,'a')),
  ]);
  return {examples,P,R,N,V,B,add,sub,mul,div};
})();

function buildRationalPower(cfg){
  const example=RP.examples.find(e=>e.group===(cfg.example||'6.1'));
  if(!example) throw 'Вибери приклад зі списку.';
  return {...example,steps:example.rows};
}
function rpFields(cfg,id){
  return `<div class="field"><label class="fl" for="${id}">Приклад</label><select id="${id}">${RP.examples.map(e=>`<option value="${e.group}"${e.group===(cfg.example||'6.1')?' selected':''}>${esc(e.title)}</option>`).join('')}</select></div><p class="helper">Вибери готовий приклад. Кожний приклад має покроковий розбір.</p>`;
}
registerTool('rational-power',{
  name:'Степінь з раціональним показником',icon:'aʳ',color:'var(--primary)',bg:'var(--primary-l)',
  inputHint:'Вибери інший приклад і натисни «Показати розв’язання».',
  freeHint:'Вибери приклад і переглянь його розв’язання крок за кроком',
  build:buildRationalPower,
  view(m,ctx){
    return `<div class="rp-sheet">${m.condition?`<p class="rp-condition">Умова: ${esc(m.condition)}</p>`:''}${m.steps.slice(0,ctx.index+1).map((s,i)=>{
      // Крок скорочення домальовує вже записаний дріб.
      if(s.cancelRow!=null) return '';
      const cancelStep=m.steps.findIndex(st=>st.cancelRow===i);
      const cancelled=cancelStep>=0&&ctx.index>=cancelStep;
      const current=i===ctx.index||ctx.step.cancelRow===i;
      const pen={writing:!!ctx.anim&&i===ctx.index,order:0};
      let formula=s.parts.map((p,j)=>(j?hwGlyphs('=',pen):'')+renderFormula(p,pen)).join('');
      if(cancelled){
        const strokePen={writing:!!ctx.anim&&ctx.index===cancelStep,order:0};
        formula=formula.replace(/(<span[^>]* data-fid="rp-cancel-(?:top|bottom)"[^>]*>)/g,tag=>
          tag+`<svg class="rp-strike" viewBox="0 0 100 100" preserveAspectRatio="none" aria-hidden="true"><path class="hwa" d="M3 92 L97 8" pathLength="100"${hwTick(strokePen,'rpstrike',.45,3)}/></svg>`);
      }
      return `<section class="rp-row${current?' rp-current':''}${i===m.steps.length-1?' rp-answer':''}"><div class="rp-label">${i===0?'Умова':i===m.steps.length-1?'Відповідь':'Перетворення'}</div><div class="fml" role="img" aria-label="${esc(s.parts.map(fmlText).join(' = '))}">${formula}</div></section>`;
    }).join('')}</div>`;
  },
  prepare:(m,from,to)=>to===from+1?{writing:true}:null,
  inputs:c=>rpFields(c,'i_rpexample'),read:v=>({example:v('i_rpexample')}),
  summary:c=>RP.examples.find(e=>e.group===(c.example||'6.1'))?.title||'Приклад',
  editorFields:c=>rpFields(c,'f_rpexample'),readEditor:v=>({example:v('f_rpexample')}),
});

